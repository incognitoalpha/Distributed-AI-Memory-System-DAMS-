package com.aimemory.memory.domain.enums;

/**
 * Enumeration of memory types supported by the system.
 *
 * @author agent
 * @since 1.0.0
 */
public enum MemoryType {
    /**
     * Episodic memory - represents specific experiences or events.
     */
    EPISODIC,

    /**
     * Semantic memory - represents general knowledge or facts.
     */
    SEMANTIC
}